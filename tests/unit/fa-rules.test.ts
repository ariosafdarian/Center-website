import { describe, it, expect } from 'vitest';
import { lintFaText } from '../../scripts/fa-rules';

const rules = (s: string) => lintFaText(s).map((r) => r.rule);

describe('lint:fa rules', () => {
  it.each([
    ['این کار توسط مرکز است', 'توسط'],
    ['این مرکز می‌باشد', 'می‌باشد'],
    ['کار انجام می‌شود', 'انجام می‌دهد'],
    ['ارزیابی صورت می‌گیرد', 'صورت می‌گیرد'],
    ['از طریق شبکه', 'از طریق'],
    ['در راستای هدف', 'در راستای'],
    ['مرکز پیشرفت هوش مصنوعی و ربات', 'نام مرکز'],
    ['دربارهٔ مرکز هوش مصنوعی', 'نام مرکز'],
    ['شرکت رباتیک', 'رباتیک'],
    ['پیمانکار فنی', 'پیمانکار'],
    ['لیگ فایت', 'لیگ فایت'],
    ['پروانه بگیرید', 'پروانه'],
    ['العلم سلطان', 'نام طرح'],
    ['پلکان پیشرفت', 'پلکان پیشرفت'],
    ['شرکت هوش آفرین', 'هوش آفرین'],
    ['رباتي', 'ی عربی'],
    ['كار', 'ک عربی'],
    ['ما می کنیم', 'می با فاصله'],
    ['ربات ها', 'ها با فاصله'],
    ['سال 1405', 'رقم لاتین'],
  ])('%s → %s', (text, rule) => expect(rules(text)).toContain(rule));

  it.each([
    'مرکز پیشرفت هوش مصنوعی و انقلاب ربات‌ها',
    'وصل می‌کنیم، می‌سنجیم، تضمین می‌کنیم.',
    'پروانهٔ صنفی',
    'سال ۱۴۰۵',
    'پیوند را درست بنویسید؛ مانند example.com/me.',
    'شناسه: {id}',
    'بازارچهٔ API و H2',
    'ایمیل را بنویسید؛ مانند name@example.com.',
    'English only 2026',
  ])('clean: %s', (text) => expect(rules(text)).toEqual([]));
});
